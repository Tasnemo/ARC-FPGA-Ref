#!/usr/bin/env python3
"""Builds web/arc-ref-console.html: the whole console in one file.

ES modules don't load from file://, so the multi-file page needs a local web
server. The bundle inlines the CSS and joins the modules into one classic
script, so on Windows or macOS you can double-click it in Chrome/Edge
without installing anything.

    python3 tools/bundle_web.py           # rebuild
    python3 tools/bundle_web.py --check   # fail if the committed bundle is stale
"""
import pathlib
import re
import sys

WEB = pathlib.Path(__file__).resolve().parent.parent / "web"
OUT = WEB / "arc-ref-console.html"
MODULES = ["protocol.js", "serial.js", "sim.js", "app.js"]   # dependency order

IMPORT_RE = re.compile(r"^import\s[\s\S]*?\sfrom\s+'[^']+';\s*$", re.M)
EXPORT_RE = re.compile(r"^export\s+", re.M)


def build():
    html = (WEB / "index.html").read_text(encoding="utf-8")
    css = (WEB / "css" / "style.css").read_text(encoding="utf-8")
    parts = []
    for name in MODULES:
        src = (WEB / "js" / name).read_text(encoding="utf-8")
        src = EXPORT_RE.sub("", IMPORT_RE.sub("", src))
        parts.append(f"// ---- {name}\n{src.strip()}\n")
    js = "(() => {\n'use strict';\n" + "\n".join(parts) + "})();\n"

    link = '<link rel="stylesheet" href="css/style.css">'
    script = '<script type="module" src="js/app.js"></script>'
    assert link in html and script in html, "index.html layout changed; update bundle_web.py"
    banner = "<!-- Generated by tools/bundle_web.py from web/index.html, css/ and js/. Do not edit. -->\n"
    html = html.replace("<!doctype html>\n", "<!doctype html>\n" + banner, 1)
    html = html.replace(link, f"<style>\n{css}</style>")
    html = html.replace(script, f"<script>\n{js}</script>")
    return html


def main():
    html = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != html:
            sys.exit("web/arc-ref-console.html is stale; run python3 tools/bundle_web.py")
        print("bundle up to date")
        return
    OUT.write_text(html, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(WEB.parent)} ({len(html) // 1024} KiB)")


if __name__ == "__main__":
    main()
